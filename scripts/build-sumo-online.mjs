import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

// Import the pinned browser-free v1.3 engine without eval/VM in the Worker.
const root = new URL("../", import.meta.url);
const sourcePath = "public/arcade-games/royal-sumo/original/royal_sumo_crownfall_v1.3.0.html";
const source = await readFile(new URL(sourcePath, root), "utf8");
const start = source.indexOf("/* ---- core/util.js ---- */");
const end = source.indexOf("/* ---- core/slots.js ---- */");
if (start < 0 || end <= start) throw new Error("Pinned Sumo core module boundaries are missing");
let core = source.slice(start, end);
const originalRng = "function mulberry32(a){return function(){a|=0;a=a+0x6D2B79F5|0;let t=Math.imul(a^a>>>15,1|a);t=t+Math.imul(t^t>>>7,61|t)^t;return((t^t>>>14)>>>0)/4294967296}}";
if (!core.includes(originalRng)) throw new Error("Pinned Sumo RNG changed; review persistence instrumentation");
// State visibility only: the arithmetic and exact draw order remain original.
core = core.replace(originalRng, "function mulberry32(a){const rng=function(){a|=0;a=a+0x6D2B79F5|0;rng.state=a>>>0;let t=Math.imul(a^a>>>15,1|a);t=t+Math.imul(t^t>>>7,61|t)^t;return((t^t>>>14)>>>0)/4294967296};rng.state=a>>>0;return rng}");
const extractModule = name => {
  const a = source.indexOf(`/* ---- core/${name}.js ---- */`);
  const b = source.indexOf("/* ---- core/", a + 1);
  if (a < 0 || b < a) throw new Error(`Missing Sumo ${name} module`);
  return source.slice(a, b);
};
const output = `/* eslint-disable -- Generated pinned upstream source; adapter is linted separately. */
// Generated by scripts/build-sumo-online.mjs. Do not edit.
// Source: ${sourcePath}; SHA-256 ${createHash("sha256").update(source).digest("hex")}
${core}${extractModule("seed")}${extractModule("cup")}
export const { Sim } = M_core_sim;
export const { MAPS, MAP_ORDER } = M_core_maps;
export const { FIXED_DT } = M_core_tune;
export const { mulberry32 } = M_core_util;
export const { normalizeOpts } = M_core_options;
export const { deriveSeed } = M_core_seed;
export const { cupOrder, newCup, scoreStage, isFinalStage, standings, champions, rankMatch } = M_core_cup;
`;
const destination = new URL("lib/arcade/online/sumo-core.mjs", root);
await writeFile(destination, output);
console.log(`Generated ${fileURLToPath(destination)}`);
