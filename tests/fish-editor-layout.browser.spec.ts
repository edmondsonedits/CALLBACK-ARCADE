import { expect, test } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import { setupFish, completeMain, openScreens, openFish } from "./fixtures/fish-room";

test.setTimeout(300_000);

test("compact fish controls, zoom-aware tool preview, and submit fit the phone viewport", async ({ browser }) => {
  const room = await setupFish(browser, 3);
  try {
    await completeMain(room);
    await openScreens(room);
    await openFish(room, "peaceful");
    const page = room.pages[0]!;
    const editor = page.getByRole("region", { name: "Fish drawing editor", exact: true });
    await expect(editor).toBeVisible();
    await editor.getByRole("button", { name: "Got it", exact: true }).click();

    await mkdir(".logs/fish-editor-layout", { recursive: true });
    for (const viewport of [{ width: 320, height: 568 }, { width:393,height:700 }, { width: 667, height: 375 }]) {
      await page.setViewportSize(viewport);
      await expect(editor).toBeVisible();
      await expect.poll(() => editor.evaluate(el => Math.round(el.getBoundingClientRect().height))).toBeLessThanOrEqual(viewport.height);
      await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
      const stage = editor.locator("[aria-label='Fish canvas']");
      const canvas = editor.getByRole("img", { name: "Your fish. Its head faces right and tail faces left." });
      const spray = editor.getByRole("button", { name: "Spray can", exact: true });
      const colour = editor.getByRole("button", { name: "Use #529AFF", exact: true });
      const undo = editor.getByRole("button", { name: "Undo", exact: true });
      const stageBox = await stage.boundingBox();
      const canvasBox = await canvas.boundingBox();
      const sprayBox = await spray.boundingBox();
      const colourBox = await colour.boundingBox();
      const undoBox = await undo.boundingBox();
      const previewBox = await editor.getByRole("button", { name: "Preview swim", exact: true }).boundingBox();
      const submit = editor.getByRole("button", { name: "Send fish", exact: true });
      const submitBox = await submit.boundingBox();
      const editorBox = await editor.boundingBox();
      const viewportHeight = page.viewportSize()!.height;
      expect(stageBox).not.toBeNull();
      expect(canvasBox).not.toBeNull();
      expect(sprayBox).not.toBeNull();
      expect(colourBox).not.toBeNull();
      expect(undoBox).not.toBeNull();
      expect(previewBox).not.toBeNull();
      expect(submitBox).not.toBeNull();
      expect(editorBox!.y).toBeGreaterThanOrEqual(0);
      expect(stageBox!.width).toBeGreaterThan(130);
      expect(stageBox!.height).toBeGreaterThan(85);
      expect(canvasBox!.width).toBeGreaterThan(100);
      expect(stageBox!.width).toBeGreaterThan(viewport.width - 12);
      expect(sprayBox!.y).toBeGreaterThanOrEqual(stageBox!.y + stageBox!.height - 1);
      expect(colourBox!.y).toBeGreaterThanOrEqual(stageBox!.y + stageBox!.height - 1);
      expect(sprayBox!.height).toBeGreaterThanOrEqual(44);
      expect(colourBox!.height).toBeGreaterThanOrEqual(44);
      expect(undoBox!.y + undoBox!.height).toBeLessThanOrEqual(viewportHeight);
      expect(submitBox!.y + submitBox!.height).toBeLessThanOrEqual(viewportHeight);
      expect(previewBox!.height).toBeLessThanOrEqual(56);
      await expect(undo).toBeVisible();
      await expect(editor.getByRole("button", { name: "Preview swim", exact: true })).toBeVisible();
      await expect(editor.locator("dialog")).toHaveCount(0);
      await page.screenshot({ path: `.logs/fish-editor-layout/${viewport.width}x${viewport.height}.png` });
    }

    await page.setViewportSize({ width: 393, height: 700 });
    const headerSubmit = await editor.getByRole("button", { name: "Send fish", exact: true }).boundingBox();
    expect(headerSubmit!.y + headerSubmit!.height).toBeLessThanOrEqual(700);

    await editor.getByRole("button", { name: "Spray can", exact: true }).click();
    const settings = editor.getByRole("region", { name: "Tool settings", exact: true });
    await expect(settings).toBeVisible();
    const stampPreview = editor.getByTestId("fish-tool-preview");
    await expect(stampPreview).toBeVisible();
    const submitWithSettings = await editor.getByRole("button", { name: "Send fish", exact: true }).boundingBox();
    expect(submitWithSettings!.y + submitWithSettings!.height).toBeLessThanOrEqual(page.viewportSize()!.height);
    expect(await stampPreview.evaluate(canvas => (canvas as HTMLCanvasElement).getContext("2d")!.getImageData(0, 0, 1024, 768).data.some((value, index) => index % 4 === 3 && value > 0))).toBe(true);
    await settings.getByRole("slider", { name: "Spray size", exact: true }).fill("120");
    await settings.getByRole("slider", { name: "Spray opacity", exact: true }).fill("70");
    const settingsBox = await settings.boundingBox();
    expect(settingsBox!.width).toBeLessThanOrEqual((page.viewportSize()!.width * 0.55));
    expect(await stampPreview.evaluate(canvas => (canvas as HTMLCanvasElement).getContext("2d")!.getImageData(0, 0, 1024, 768).data.some((value, index) => index % 4 === 3 && value > 0))).toBe(true);
    await page.screenshot({ path: ".logs/fish-editor-layout/tool-preview.png" });
    await settings.getByRole("button", { name: "Done", exact: false }).click();
    await expect(settings).toBeHidden();
    const fishCanvas = editor.getByRole("img", { name: "Your fish. Its head faces right and tail faces left." });
    const strip = editor.locator('[aria-label="Swipe for more tools"]');
    const stripBox = (await strip.boundingBox())!;
    await page.mouse.move(stripBox.x + stripBox.width - 12, stripBox.y + 20); await page.mouse.down();
    await page.mouse.move(stripBox.x + 12, stripBox.y + 20, { steps: 8 }); await page.mouse.up();
    expect(await strip.evaluate(el => el.scrollLeft)).toBeGreaterThan(0);
    await editor.getByRole("button", { name: "Brush", exact: true }).click();
    await expect(settings).toBeVisible();
    const closeBox = (await fishCanvas.boundingBox())!;
    await page.mouse.click(closeBox.x + closeBox.width * .8, closeBox.y + closeBox.height * .5);
    await expect(settings).toBeHidden();
    await expect(editor.getByRole("button", { name: "Undo", exact: true })).toBeDisabled();
    const gradientEnd = editor.getByRole("button", { name: "Use #E0527D", exact: true });
    await gradientEnd.scrollIntoViewIfNeeded();
    await gradientEnd.click();
    await expect(gradientEnd).toHaveAttribute("aria-pressed", "true");
    await expect(editor.locator('[aria-label="Ink colour"] > button')).toHaveCount(28);
    const canvasBox = (await fishCanvas.boundingBox())!;
    await page.mouse.click(canvasBox.x + canvasBox.width * 0.53, canvasBox.y + canvasBox.height * 0.5);
    await expect(editor.getByRole("button", { name: "Undo", exact: true })).toBeEnabled();
    await expect(editor.getByRole("button", { name: "Parts", exact: true })).toHaveCount(0);
    await expect(editor.getByRole("button", { name: "Body", exact: true })).toBeVisible();
    await editor.getByRole("button", { name: "Body", exact: true }).click();
    const transparentCorner = (await fishCanvas.boundingBox())!;
    await page.mouse.click(transparentCorner.x + transparentCorner.width * .08, transparentCorner.y + transparentCorner.height * .08);
    await expect(editor.getByRole("button", { name: "Undo", exact: true })).toBeEnabled();
    await expect.poll(() => fishCanvas.evaluate(canvas => (canvas as HTMLCanvasElement).getContext("2d")!.getImageData(82, 61, 1, 1).data[3])).toBeGreaterThan(0);
    const originalBodyPixel = await fishCanvas.evaluate(canvas => [...(canvas as HTMLCanvasElement).getContext("2d")!.getImageData(82, 61, 1, 1).data]);
    await editor.getByRole("button", { name: "Paint fish", exact: true }).click();
    await editor.getByRole("button", { name: "Use #E05252", exact: true }).click();
    await editor.getByRole("button", { name: "Brush", exact: true }).click();
    await editor.getByRole("region", { name: "Tool settings", exact: true }).getByRole("button", { name: "Done", exact: false }).click();
    await page.mouse.click(transparentCorner.x + transparentCorner.width * .08, transparentCorner.y + transparentCorner.height * .08);
    const drawnBodyPixel = await fishCanvas.evaluate(canvas => [...(canvas as HTMLCanvasElement).getContext("2d")!.getImageData(82, 61, 1, 1).data]);
    expect(drawnBodyPixel[3]).toBe(originalBodyPixel[3]);
    expect(drawnBodyPixel).not.toEqual(originalBodyPixel);
    await editor.getByRole("button", { name: "Eraser", exact: true }).click();
    await editor.getByRole("region", { name: "Tool settings", exact: true }).getByRole("button", { name: "Done", exact: false }).click();
    await page.mouse.click(transparentCorner.x + transparentCorner.width * .08, transparentCorner.y + transparentCorner.height * .08);
    const erasedBodyPixel = await fishCanvas.evaluate(canvas => [...(canvas as HTMLCanvasElement).getContext("2d")!.getImageData(82, 61, 1, 1).data]);
    expect(erasedBodyPixel).toEqual(originalBodyPixel);
    const fillPoint = (await fishCanvas.boundingBox())!;
    const sampleBeforeFill = await fishCanvas.evaluate(canvas => [...(canvas as HTMLCanvasElement).getContext("2d")!.getImageData(614, 461, 1, 1).data]);
    await editor.getByRole("button", { name: "Use #529AFF", exact: true }).click();
    await editor.getByRole("button", { name: "Fill", exact: true }).click();
    await page.mouse.click(fillPoint.x + fillPoint.width * .6, fillPoint.y + fillPoint.height * .6);
    await expect.poll(() => fishCanvas.evaluate(canvas => (canvas as HTMLCanvasElement).getContext("2d")!.getImageData(614, 461, 1, 1).data[2])).toBeGreaterThan(sampleBeforeFill[2]);
    await editor.getByRole("button", { name: "Eraser", exact: true }).click();
    await editor.getByRole("region", { name: "Tool settings", exact: true }).getByRole("button", { name: "Done", exact: false }).click();
    await page.mouse.click(fillPoint.x + fillPoint.width * .6, fillPoint.y + fillPoint.height * .6);
    await expect.poll(() => fishCanvas.evaluate(canvas => [...(canvas as HTMLCanvasElement).getContext("2d")!.getImageData(614, 461, 1, 1).data])).toEqual(sampleBeforeFill);
    const sendBox = await editor.getByRole("button", { name: "Send fish", exact: true }).boundingBox();
    expect(sendBox!.y + sendBox!.height).toBeLessThanOrEqual(page.viewportSize()!.height);
    await expect(editor.locator("[aria-label='Fish canvas']")).toBeVisible();
  } finally {
    await room.close();
  }
});
